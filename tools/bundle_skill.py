#!/usr/bin/env python3
"""Write skills/brogue/scripts/{lint,ground}.py from the package source.

The skill must work with nothing installed, so its scripts are single files.
They are generated from src/brogue and a test checks they are in sync.

    python tools/bundle_skill.py
"""
from __future__ import annotations

import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SRC, OUT = ROOT / "src/brogue", ROOT / "skills/brogue/scripts"

MAIN = '''

def main() -> int:
    import argparse
    import sys
    parser = argparse.ArgumentParser(description="Strike from a draft what the request never said.")
    parser.add_argument("request", help="file with what the writer was told (the brief, or the text being rewritten)")
    parser.add_argument("draft", help="file with the draft to check")
    parser.add_argument("--model", default=None, help="model id; default: haiku for the claude CLI")
    args = parser.parse_args()
    request = Path(args.request).read_text(encoding="utf-8")
    draft = Path(args.draft).read_text(encoding="utf-8")
    try:
        result = ground(request, draft, connect("auto", args.model))
    except LLMError as err:
        print(f"ground: no model available ({err}); check the draft by hand as SKILL.md describes", file=sys.stderr)
        return 3
    print(result.text)
    print(result.summary(), file=sys.stderr)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
'''


def body(name: str) -> str:
    text = (SRC / name).read_text()
    text = re.sub(r'^""".*?"""\n', "", text, count=1, flags=re.DOTALL)
    text = re.sub(r"^from __future__ import annotations\n", "", text, flags=re.M)
    return re.sub(r"^from \.\w* import .*\n", "", text, flags=re.M)


def ground_script() -> str:
    head = ('#!/usr/bin/env python3\n"""Brogue grounding pass, as one file. Generated by tools/bundle_skill.py; '
            'do not edit.\n\nUsage: python scripts/ground.py request.txt draft.txt\n\nUses the `claude` CLI if it is '
            'installed, else any OpenAI-compatible endpoint set\nby BROGUE_BASE_URL, BROGUE_API_KEY and BROGUE_MODEL. '
            'Prints the grounded draft;\nwhat was removed goes to stderr.\n"""\nfrom __future__ import annotations\n\n'
            'from pathlib import Path\n')
    parts = [body("llm.py"), body("guard.py").replace("class GuardReport", "class GuardReport", 1),
             body("ground.py").replace("guard.facts", "facts")]
    return head + "\n".join(parts) + MAIN


def lint_script() -> str:
    return (SRC / "lint.py").read_text()


def main() -> None:
    (OUT / "ground.py").write_text(ground_script())
    (OUT / "lint.py").write_text(lint_script())
    print("wrote skills/brogue/scripts/ground.py and lint.py")


if __name__ == "__main__":
    main()
